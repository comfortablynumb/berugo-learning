/**
 * Section: circuits and non-uniform computation.
 *
 * The measurement is size against depth, with correctness checked over every
 * input at every width. At six bits the ripple-carry carry-out is 21 gates and
 * 11 deep; the carry-lookahead one is 28 gates and 3 deep, constant in the
 * width. That is the same trade the ALU section in M33 makes physically, and it
 * is why carry-lookahead exists.
 *
 * The theoretical half is non-uniformity: a circuit family is a different
 * object per input length and nothing requires a program to generate it, which
 * is why P/poly contains undecidable languages.
 */
(function (root) {
  'use strict';

  const SECTION_ID = 'circuits-and-non-uniform-computation';
  let panel = null;

  function init(app) {
    app.state.subscribe('navigation', function (event) {
      if (event.section !== SECTION_ID || !app.markRendered(SECTION_ID)) return;
      render(app);
    });
  }

  function diagram() {
    return {
      title: 'Diagram — a circuit’s layers, with depth annotated',
      caption: 'Size is the gate count and depth is the longest path from an input to the ' +
        'output, and the two readings are physical: size is area on a die and depth is latency, ' +
        'because every gate on the critical path has to settle before the next one can start. ' +
        'Gates at the same level are independent, so depth is also PARALLEL TIME — a circuit of ' +
        'depth d computes in d steps given as many processors as you like. That is why NC, the ' +
        'class of problems with polylogarithmic-depth polynomial-size circuits, is the formal ' +
        'meaning of "efficiently parallelisable", and why a P-complete problem is one nobody ' +
        'knows how to parallelise at all.',
      definition: [
        'graph BT',
        '    x0[x0] --> g0["AND"]',
        '    x1[x1] --> g0',
        '    x2[x2] --> g1["AND"]',
        '    x3[x3] --> g1',
        '    g0 --> g2["OR"]',
        '    g1 --> g2',
        '    g2 --> out["output — depth 2, size 3"]'
      ].join('\n')
    };
  }

  function orientation() {
    return [
      '**A Boolean circuit is a directed acyclic graph of gates, and it works for exactly one ' +
        'input length.** That is the first thing to hold onto, because everything strange about ' +
        'this model follows from it. To handle every length you need a FAMILY — one circuit per ' +
        'n — and a family is a different kind of object from an algorithm.',
      '**Size is area and depth is latency.** Size counts the gates; depth is the longest path ' +
        'from an input to the output. Both readings are physical, and the demo multiplies depth ' +
        'by a gate delay to get a propagation time, which is exactly how a hardware engineer ' +
        'reads the same number.',
      '**Depth is also parallel time.** Every gate at the same level can fire simultaneously, so ' +
        'a depth-d circuit computes in d steps given enough hardware. NC is the class of ' +
        'problems with polylogarithmic depth and polynomial size — the formal meaning of ' +
        '"parallelises well" — and whether NC = P is open.',
      '**Non-uniformity is the model\'s strangest feature and it is not a bug.** Nothing ' +
        'requires the family to be generated by a program. A family can differ arbitrarily from ' +
        'one length to the next, which means P/poly — polynomial-size families — contains ' +
        'UNDECIDABLE languages: encode the answer to the halting problem one bit per length, and ' +
        'each individual circuit is a constant and perfectly legal.',
      '**That is exactly why circuit lower bounds are the strongest kind.** Proving a function ' +
        'needs large circuits rules out every algorithm AND every non-uniform family, including ' +
        'ones nobody could write down. It is also why the bounds are so hard to get: proving ' +
        'NP is outside P/poly would prove P ≠ NP.',
      '**PARITY is not in AC⁰, and that is one of the few unconditional lower bounds anybody ' +
        'has.** AC⁰ is constant depth, unbounded fan-in, polynomial size. Furst, Saxe and Sipser ' +
        'showed PARITY needs more, and Håstad made it tight with the switching lemma: ' +
        'exponential size for constant depth. OR sits comfortably in AC⁰ and PARITY does not, ' +
        'and the demo builds both.',
      '**Unbounded fan-in is what makes constant depth possible at all.** With gates limited to ' +
        'two inputs, computing anything over n bits needs at least log n depth just to see every ' +
        'input. AC⁰ allows a single gate to take all n, which is a real hardware idealisation — ' +
        'a wide gate is slower in practice — and it is why AC⁰ and NC¹ are different classes.',
      '**The barriers explain why so little is proved.** Relativisation blocks any argument that ' +
        'would work with an oracle attached; natural proofs (Razborov and Rudich) show that any ' +
        'lower-bound technique that is broad and constructive would break the ' +
        'pseudorandom-generator assumptions cryptography rests on. Almost every method anyone ' +
        'has tried falls into one of the two.'
    ];
  }

  function config() {
    return {
      sectionId: SECTION_ID,
      orientation: orientation(),
      demo: {
        title: 'Interactive demo — build a family, measure size and depth, check every input',
        markup: root.CircuitTemplate.render()
      },
      diagram: diagram(),
      insight: '**Depth is latency and size is area — this is the same trade the ALU section in ' +
        'M33 makes physically, and it is why carry-lookahead exists.** The demo puts a number ' +
        'on it: at six bits, a ripple-carry carry-out is 21 gates and 11 levels deep, and a ' +
        'carry-lookahead one is 28 gates and 3 levels — a third more area for a latency that ' +
        'stops growing with the width. Every processor you have used made that trade, and the ' +
        'same shape recurs far from hardware: a prefix-sum scan is a depth-reduction of a ' +
        'sequential fold, a tree reduction in a data-parallel job is the same manoeuvre, and a ' +
        'CDN is a depth reduction on a network. Whenever a computation is a long dependency ' +
        'chain, the question is whether you can spend width to shorten it, and this section is ' +
        'the general form of that question.'
    };
  }

  function render(app) {
    root.jQuery('#' + SECTION_ID + '-content').html(app.shell.render(config()));
    app.shell.mount({ sectionId: SECTION_ID, app: app });

    panel = root.ControlPanel.mount({
      controls: root.CircuitTemplate.controls,
      onChange: function () { update(); }
    });
    update();
  }

  /* ------------------------------------------------------------ measuring */

  function referenceFor(name, width) {
    const references = root.Circuits.references();

    if (name.indexOf('parity') === 0) return references.parity();
    if (name.indexOf('or') === 0) return references.or();
    return references.carry(width);
  }

  const builtFor = root.Helpers.memoise(function (key) {
    const parts = key.split('\n');
    const width = Number(parts[1]);
    const circuit = root.Circuits.families()[parts[0]](width);

    return { circuit: circuit, size: root.Circuits.size(circuit),
      depth: root.Circuits.depth(circuit),
      correct: root.Circuits.computes(circuit, circuit.inputs,
        referenceFor(parts[0], width)) };
  });

  const growthFor = root.Helpers.memoise(function (key) {
    const parts = key.split('\n');
    const delay = Number(parts[1]);

    return [2, 3, 4, 5, 6, 7, 8].map(function (width) {
      const state = builtFor(parts[0] + '\n' + width);

      return { width: width, size: state.size, depth: state.depth,
        delay: state.depth * delay, correct: state.correct };
    });
  });

  function update() {
    const values = panel.values();
    const key = values['cir-family'] + '\n' + values['cir-width'];
    const state = builtFor(key);

    paintMetrics(state, values);
    paintLayers(state);
    paintGrowth(values);
    paintArrangements(values['cir-width'], values['cir-latency']);
    paintTruth(state, values['cir-family']);
    paintClasses();
  }

  function paintMetrics(state, values) {
    root.MetricGrid.update({
      'cir-size': { value: root.Format.exact(state.size) + ' gates',
        note: 'inputs and constants are not counted; this is the area' },
      'cir-depth': { value: root.Format.exact(state.depth),
        note: 'the longest path from an input to the output, which is the latency' },
      'cir-correct': { value: state.correct ? 'yes' : 'NO',
        note: root.Format.exact(Math.pow(2, state.circuit.inputs)) +
          ' input combinations, every one checked against the function' },
      'cir-delay': { value: root.Format.exact(state.depth * Number(values['cir-latency'])) +
        ' ps',
      note: root.Format.exact(state.depth) + ' levels at ' + values['cir-latency'] +
        ' ps per gate' }
    });
  }

  function paintLayers(state) {
    const layers = root.Circuits.layers(state.circuit);

    root.jQuery('#cir-layers').html(layers.map(function (level, i) {
      return root.Helpers.escapeHtml('level ' + i + ': ' + level.map(function (gate) {
        return gate.op === 'input' ? gate.id : gate.op + '(' + gate.inputs.length + ')';
      }).join(' '));
    }).join('<br>'));

    root.Helpers.setText('cir-layers-note',
      'Every gate on a level can fire at the same instant, because none of them depends on ' +
      'another on that level. The number of levels is therefore the parallel time, and the ' +
      'number in the brackets is a gate\'s fan-in. Watch that number when you switch to the ' +
      'unbounded-fan-in families: constant depth is bought entirely by letting one gate take ' +
      'every input at once, which is a real hardware cost the model chooses not to charge for.');
  }

  function paintGrowth(values) {
    root.jQuery('#cir-growth tbody').html(
      growthFor(values['cir-family'] + '\n' + values['cir-latency']).map(function (row) {
        return '<tr><td class="mono">' + row.width + '</td><td class="mono">' + row.size +
          '</td><td class="mono">' + row.depth + '</td><td class="mono">' + row.delay +
          ' ps</td><td class="mono">' + (row.correct ? 'yes' : 'NO') + '</td></tr>';
      }).join(''));

    root.Helpers.setText('cir-growth-note',
      'The correctness column is checked exhaustively at every width — all 2^inputs ' +
      'combinations, compared against the function written independently. That matters more ' +
      'than it looks: a circuit family that grows beautifully and computes the wrong thing is ' +
      'the easiest mistake to make here, and a size-and-depth table with no correctness column ' +
      'beside it is measuring the wrong object.');
  }

  function paintArrangements(width, delay) {
    const groups = {
      or: ['orChain', 'orTree', 'orFlat'],
      parity: ['parityChain', 'parityTree'],
      carry: ['rippleCarry', 'carryLookahead']
    };
    const rows = [];

    Object.keys(groups).forEach(function (name) {
      groups[name].forEach(function (family) {
        const state = builtFor(family + '\n' + width);

        rows.push({ family: state.circuit.label, size: state.size, depth: state.depth,
          fanIn: family === 'orFlat' || family === 'carryLookahead' ? 'unbounded' : '2',
          cost: state.depth * Number(delay) + ' ps of latency, ' + state.size + ' gates of area' });
      });
    });
    root.jQuery('#cir-arrangements tbody').html(rows.map(function (row) {
      return '<tr><td class="mono">' + root.Helpers.escapeHtml(row.family) +
        '</td><td class="mono">' + row.size + '</td><td class="mono">' + row.depth +
        '</td><td class="mono">' + row.fanIn + '</td><td>' + row.cost + '</td></tr>';
    }).join(''));

    root.Helpers.setText('cir-arrangements-note',
      'Three groups, and each teaches something different. OR as a chain against OR as a tree ' +
      'is the free lunch: identical size, logarithmic instead of linear depth, and the chain ' +
      'was simply worse. OR flat against OR as a tree is the real purchase — constant depth, ' +
      'bought with unbounded fan-in. And ripple-carry against carry-lookahead is the trade ' +
      'that ships in silicon: more gates, constant depth, and every processor you have used ' +
      'chose the second.');
  }

  function paintTruth(state, family) {
    const rows = root.Circuits.truthTable(state.circuit,
      Math.min(state.circuit.inputs, 4));
    const reference = referenceFor(family, Number(state.circuit.inputs) / 2);

    root.jQuery('#cir-truth tbody').html(rows.slice(0, 10).map(function (row) {
      const expected = reference(row.bits) ? 1 : 0;

      return '<tr><td class="mono">' + row.bits.join('') + '</td><td class="mono">' +
        row.output + '</td><td class="mono">' +
        (state.circuit.inputs <= 4 ? expected : '—') + '</td><td class="mono">' +
        (state.circuit.inputs <= 4 ? (row.output === expected ? 'yes' : 'NO') : 'see above') +
        '</td></tr>';
    }).join(''));

    root.Helpers.setText('cir-truth-note',
      'The first ten rows, at up to four inputs; the full check runs over every combination and ' +
      'is reported in the correctness metric. A truth table is the only complete specification a ' +
      'Boolean function has, which is both why exhaustive checking is possible here and why it ' +
      'stops being possible almost immediately — sixteen inputs is already sixty-five thousand ' +
      'rows, and thirty-two is beyond reach.');
  }

  function paintClasses() {
    root.jQuery('#cir-classes tbody').html(root.Circuits.CLASSES.map(function (row) {
      return '<tr><td class="mono">' + row.name + '</td><td class="mono">' + row.depth +
        '</td><td class="mono">' + row.fanIn + '</td><td>' +
        root.Helpers.escapeHtml(row.contains) + '</td><td>' +
        root.Helpers.escapeHtml(row.excludes) + '</td></tr>';
    }).join(''));

    root.Helpers.setText('cir-classes-note',
      'Read the last column. Only one row has a real entry — PARITY is provably not in AC⁰ — ' +
      'and every other class excludes nothing anybody can name. The P/poly row is the extreme ' +
      'case: it contains undecidable languages, and we still cannot exhibit an explicit function ' +
      'that needs superpolynomial circuits. That is the state of circuit complexity, and the ' +
      'natural-proofs barrier says the obvious approaches cannot fix it.');
  }

  root.SectionRegistry.register({ id: SECTION_ID, init: init });
}(window));
